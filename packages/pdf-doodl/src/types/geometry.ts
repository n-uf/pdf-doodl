/**
 * Geometry type definitions
 */

/**
 * 2D point in content space
 */
export interface Point {
  x: number;
  y: number;
}

/**
 * Size dimensions
 */
export interface Size {
  width: number;
  height: number;
}

/**
 * Bounding box
 */
export interface Bounds {
  x: number;
  y: number;
  width: number;
  height: number;
}

